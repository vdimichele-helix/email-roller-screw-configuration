// Get all unique diameters
export const DIAMETERS = [...new Set(
  Object.keys(LOAD_CAPACITY_DATA).map(k => parseInt(k.split("-")[0]))
)].sort((a, b) => a - b);

// Get available leads for a given diameter
export function getAvailableLeads(diameter) {
  if (!diameter) return [];
  return Object.keys(LOAD_CAPACITY_DATA)
    .filter(k => k.startsWith(`${diameter}-`))
    .map(k => parseInt(k.split("-")[1]))
    .sort((a, b) => a - b);
}

// Get load capacity for diameter × lead combination
export function getLoadCapacity(diameter, lead) {
  if (!diameter || !lead) return null;
  return LOAD_CAPACITY_DATA[`${diameter}-${lead}`] || null;
}